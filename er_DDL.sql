SET TIME ZONE 'UTC';


-- Reproducible setup: remove previous HW2 objects before recreating the schema.
DROP VIEW IF EXISTS hw2_user_interactions_view;

DROP TABLE IF EXISTS
    hw2_user_features_online,
    hw2_training_events,
    hw2_user_features_offline,
    hw2_movie_genres,
    hw2_ratings,
    hw2_genres,
    hw2_movies,
    hw2_users
CASCADE;


-- ============================================================
-- Business domain
-- ============================================================

CREATE TABLE hw2_users (
    user_id     INTEGER PRIMARY KEY,
    age         SMALLINT NOT NULL,
    gender      CHAR(1) NOT NULL,
    occupation  VARCHAR(100) NOT NULL,
    zip_code    VARCHAR(20) NOT NULL,

    CHECK (age > 0),
    CHECK (gender IN ('M', 'F'))
);

COMMENT ON TABLE hw2_users IS
    'MovieLens users used as the main entity for recommendation features and training events.';


CREATE TABLE hw2_movies (
    movie_id      INTEGER PRIMARY KEY,
    title         TEXT NOT NULL,
    release_date  DATE,
    imdb_url      TEXT
);

COMMENT ON TABLE hw2_movies IS
    'Movies that can be rated by users and used as recommendation candidates.';


CREATE TABLE hw2_genres (
    genre_id    SMALLINT PRIMARY KEY,
    genre_name  VARCHAR(50) NOT NULL UNIQUE
);

COMMENT ON TABLE hw2_genres IS
    'Normalized dictionary of movie genres.';


-- Bridge table implementing the many-to-many relationship
-- between movies and genres.
CREATE TABLE hw2_movie_genres (
    movie_id INTEGER NOT NULL
        REFERENCES hw2_movies(movie_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    genre_id SMALLINT NOT NULL
        REFERENCES hw2_genres(genre_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    PRIMARY KEY (movie_id, genre_id)
);

COMMENT ON TABLE hw2_movie_genres IS
    'Bridge table implementing the many-to-many relationship between movies and genres.';


-- User-to-movie interaction history from MovieLens.
CREATE TABLE hw2_ratings (
    user_id INTEGER NOT NULL
        REFERENCES hw2_users(user_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    movie_id INTEGER NOT NULL
        REFERENCES hw2_movies(movie_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    rating    SMALLINT NOT NULL,
    rating_ts TIMESTAMPTZ NOT NULL,

    PRIMARY KEY (user_id, movie_id),

    CHECK (rating BETWEEN 1 AND 5)
);

COMMENT ON TABLE hw2_ratings IS
    'Historical user ratings of movies with timestamps used as the source for feature calculation.';


-- ============================================================
-- Offline feature store
-- ============================================================

-- Every row represents one historical feature version
-- valid on the half-open interval [valid_from, valid_to).
CREATE TABLE hw2_user_features_offline (
    user_id INTEGER NOT NULL
        REFERENCES hw2_users(user_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    valid_from          TIMESTAMPTZ NOT NULL,
    valid_to            TIMESTAMPTZ,

    ratings_30d         INTEGER NOT NULL,
    avg_rating_30d      NUMERIC(3, 2),
    distinct_movies_30d INTEGER NOT NULL,
    distinct_genres_30d INTEGER NOT NULL,

    PRIMARY KEY (user_id, valid_from),

    CHECK (ratings_30d >= 0),
    CHECK (
        avg_rating_30d IS NULL
        OR avg_rating_30d BETWEEN 1 AND 5
    ),
    CHECK (distinct_movies_30d >= 0),
    CHECK (distinct_genres_30d >= 0),
    CHECK (
        valid_to IS NULL
        OR valid_to > valid_from
    )
);

COMMENT ON TABLE hw2_user_features_offline IS
    'Historical user feature snapshots for point-in-time joins.';

COMMENT ON COLUMN hw2_user_features_offline.valid_from IS
    'Inclusive start of the feature validity interval.';

COMMENT ON COLUMN hw2_user_features_offline.valid_to IS
    'Exclusive end of the validity interval; NULL means current.';


-- ============================================================
-- Training events
-- ============================================================

-- Prediction time is separated from the future observation window
-- used to construct the target label.
CREATE TABLE hw2_training_events (
    event_id BIGINT
        GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    user_id INTEGER NOT NULL
        REFERENCES hw2_users(user_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    movie_id INTEGER NOT NULL
        REFERENCES hw2_movies(movie_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    prediction_ts         TIMESTAMPTZ NOT NULL,
    label_horizon_end     TIMESTAMPTZ NOT NULL,
    high_rating_in_horizon BOOLEAN NOT NULL,

    CHECK (label_horizon_end > prediction_ts)
);

COMMENT ON TABLE hw2_training_events IS
    'Training events with prediction time separated from the future label horizon.';

COMMENT ON COLUMN hw2_training_events.prediction_ts IS
    'Prediction timestamp; joined features must already exist at this moment.';

COMMENT ON COLUMN hw2_training_events.label_horizon_end IS
    'End of the future observation window reserved for target construction.';

COMMENT ON COLUMN hw2_training_events.high_rating_in_horizon IS
    'Binary target indicating a high-rating outcome inside the label horizon.';


-- ============================================================
-- Online feature store
-- ============================================================

-- One denormalized current feature row per user
-- for low-latency inference lookup.
CREATE TABLE hw2_user_features_online (
    user_id INTEGER PRIMARY KEY
        REFERENCES hw2_users(user_id)
        ON UPDATE RESTRICT
        ON DELETE RESTRICT,

    ratings_30d         INTEGER NOT NULL,
    avg_rating_30d      NUMERIC(3, 2),
    distinct_movies_30d INTEGER NOT NULL,
    distinct_genres_30d INTEGER NOT NULL,

    feature_ts TIMESTAMPTZ NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
        DEFAULT CURRENT_TIMESTAMP,

    CHECK (ratings_30d >= 0),
    CHECK (
        avg_rating_30d IS NULL
        OR avg_rating_30d BETWEEN 1 AND 5
    ),
    CHECK (distinct_movies_30d >= 0),
    CHECK (distinct_genres_30d >= 0)
);

COMMENT ON TABLE hw2_user_features_online IS
    'Denormalized online feature store containing the latest materialized user features for low-latency inference.';

COMMENT ON COLUMN hw2_user_features_online.feature_ts IS
    'Timestamp representing the source data time of the materialized feature values.';

COMMENT ON COLUMN hw2_user_features_online.updated_at IS
    'Timestamp when the online feature row was last written to the database.';


-- ============================================================
-- Indexes
-- ============================================================

-- Main access pattern for historical point-in-time feature lookup.
CREATE INDEX hw2_idx_user_features_asof
    ON hw2_user_features_offline (user_id, valid_from DESC);

-- Guarantees at most one current feature version per user.
CREATE UNIQUE INDEX hw2_uq_user_features_current
    ON hw2_user_features_offline (user_id)
    WHERE valid_to IS NULL;

-- Supports feature calculation from recent user rating history.
CREATE INDEX hw2_idx_ratings_user_ts
    ON hw2_ratings (user_id, rating_ts DESC);

-- Supports lookup of training events by user and prediction time.
CREATE INDEX hw2_idx_training_events_user_ts
    ON hw2_training_events (user_id, prediction_ts);


-- ============================================================
-- Semantic feature layer
-- ============================================================

-- Derived semantic layer combining rating events with movie genres.
-- One rating may produce several rows because one movie can belong
-- to several genres. Referential integrity is enforced by the
-- underlying physical tables.
CREATE VIEW hw2_user_interactions_view AS
SELECT
    r.user_id,
    r.movie_id,
    r.rating,
    r.rating_ts,
    mg.genre_id
FROM hw2_ratings AS r
LEFT JOIN hw2_movie_genres AS mg
    ON mg.movie_id = r.movie_id;

COMMENT ON VIEW hw2_user_interactions_view IS
    'Derived rating-to-genre view. Referential integrity is enforced by base tables.';
